"""Create the blank gold-label file and its guide, or check a labelled file.

Usage: uv run scripts/triage/make_labelling_file.py          # writes data/triage/gold_labels.csv + labelling_guide.md
       uv run scripts/triage/make_labelling_file.py --check  # validates the labels filled in so far

The file holds 80 complaints (30 dev, 50 held out) for blind labelling: narrative and CFPB tags
only, no CFPB product or issue and no model output. It is never overwritten once it exists.
"""
import argparse
import csv
import sys

import numpy as np
import pandas as pd

from get_complaints import DEST as SLICE, NARRATIVE, SEED
from payguard.triage.taxonomy import (CATEGORY_RULES, DEFINITIONS, URGENCY_RULES, Category, Flag,
                                      Urgency)

LABELS = SLICE.with_name("gold_labels.csv")
GUIDE = SLICE.with_name("labelling_guide.md")
SPLITS = {"dev": 30, "test": 50}
INFO_COLUMNS = ["complaint_id", "split", "tags", "narrative"]
ALLOWED = {"category": {*Category}, "urgency": {*Urgency}} | {flag: {"y", "n"} for flag in Flag}
COLUMNS = INFO_COLUMNS + list(ALLOWED) + ["notes"]


def draw_gold(slice_df: pd.DataFrame) -> pd.DataFrame:
    # One copy per narrative, so a template complaint can't sit in both dev and test.
    unique = slice_df.drop_duplicates(NARRATIVE).reset_index(drop=True)
    picked = np.random.RandomState(SEED).choice(len(unique), sum(SPLITS.values()), replace=False)
    gold = unique.iloc[picked].reset_index(drop=True)
    gold.insert(0, "split", np.repeat(list(SPLITS), list(SPLITS.values())))
    gold = gold.rename(columns={"Complaint ID": "complaint_id", "Tags": "tags", NARRATIVE: "narrative"})
    return gold[INFO_COLUMNS].reindex(columns=COLUMNS, fill_value="")


def check_rows(rows: list[dict[str, str]]) -> list[str]:
    """One message per blank or invalid label cell; an empty list means the file is fully labelled."""
    problems = []
    for row in rows:
        for column, allowed in ALLOWED.items():
            value = row[column].strip().lower()
            if value not in allowed:
                problem = "blank" if not value else f"'{row[column]}' is not one of {sorted(allowed)}"
                problems.append(f"{row['complaint_id']} ({row['split']}) {column}: {problem}")
    return problems


def guide() -> str:
    def section(title: str, terms) -> str:
        return f"## {title}\n\n" + "\n".join(f"- **`{t}`**: {DEFINITIONS[t]}" for t in terms) + "\n"

    return (
        "# Labelling guide\n\n"
        f"Generated by `scripts/triage/make_labelling_file.py` from the same definitions the LLM is given.\n\n"
        "Label each row of `gold_labels.csv` from the narrative (and tags) alone:\n\n"
        "- Don't guess what's behind `XXXX` or `XX/XX/XXXX`. Label what the text supports.\n"
        "- Label the flags independently of the category: a fraud complaint can carry any flag.\n"
        "- Flags come from the narrative only. Tags (Older American, Servicemember) already send a complaint to "
        "review on their own, so set `vulnerable_customer` only when the text itself describes it.\n"
        "- Every label cell needs a value: flags are `y` or `n`, never blank once the row is done.\n"
        "- Write in `notes` whenever you're unsure or two answers seem equally right.\n"
        "- Label all `dev` rows first; `test` rows are kept aside for the final score.\n\n"
        f"{section('Category', Category)}\n{CATEGORY_RULES}\n\n"
        f"{section('Urgency', reversed(Urgency))}\n{URGENCY_RULES}\n\n"
        f"{section('Flags (y/n)', Flag)}\n"
        "When done, download as CSV, save it over `data/triage/gold_labels.csv`, then run "
        "`uv run scripts/triage/make_labelling_file.py --check`.\n"
    )


def create() -> int:
    if LABELS.exists():
        print(f"{LABELS} already exists; not overwriting it.", file=sys.stderr)
        return 1
    draw_gold(pd.read_csv(SLICE, dtype=str, keep_default_na=False)).to_csv(LABELS, index=False)
    GUIDE.write_text(guide(), encoding="utf-8")
    print(f"Wrote {LABELS} ({sum(SPLITS.values())} complaints) and {GUIDE}")
    return 0


def check() -> int:
    try:
        with LABELS.open(encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
    except FileNotFoundError:
        print(f"No {LABELS}; create it first (run without --check).", file=sys.stderr)
        return 1
    missing = set(COLUMNS) - set(reader.fieldnames or [])
    if missing:
        print(f"Columns missing: {sorted(missing)}. Was it saved as comma-separated CSV?", file=sys.stderr)
        return 1
    problems = check_rows(rows)
    print("\n".join(problems))
    unfinished = {p.split(" ", 1)[0] for p in problems}
    print(f"{len(rows) - len(unfinished)} of {len(rows)} rows fully labelled; {len(problems)} cells to fix or fill.")
    return 1 if problems else 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="validate the labels filled in so far")
    return check() if parser.parse_args().check else create()


if __name__ == "__main__":
    sys.exit(main())
