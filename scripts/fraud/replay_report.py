"""Checks a finished replay against the offline model and writes reports/fraud/replay_report.md.

Parity: the API must return exactly the scores the same MLflow run gives offline, so the replay's totals
equal the decision report's for the same transactions (no training-serving skew).
"""
import os
import platform
from typing import TYPE_CHECKING

import mlflow.sklearn
import numpy as np
import pandas as pd

from evaluate import pct, table
from get_data import SHA256
from payguard.fraud.data import FEATURES, LABEL
from payguard.fraud.evaluation import LATENCY_LIMIT_MS, at_threshold, latency_summary
from payguard.fraud.tracking import ROOT, use_local_store
from replay_panel import BIN_MIN, bin_start, hh_mm, mm_ss

if TYPE_CHECKING:
    from replay import Results

REPORT = ROOT / "reports" / "fraud" / "replay_report.md"


def offline_scores(run_id: str, *frames: pd.DataFrame) -> list[np.ndarray]:
    """Scores from the served run's model, loaded from MLflow outside the API."""
    use_local_store()
    model = mlflow.sklearn.load_model(f"runs:/{run_id}/model")
    return [model.predict_proba(f[FEATURES])[:, 1] for f in frames]


def parity(out: "Results", offline: np.ndarray, threshold: float) -> dict:
    return {"max_diff": float(np.max(np.abs(out.score - offline))),
            "mismatches": int((out.alert != (offline >= threshold)).sum())}


def counts(y: np.ndarray, scores: np.ndarray, threshold: float) -> dict:
    o = at_threshold(y, scores, threshold)
    frauds = int(y.sum())
    return {"transactions": len(y), "frauds": frauds, "alerts": o["alerts"], "caught": o["caught"],
            "false alerts": o["alerts"] - o["caught"], "missed": frauds - o["caught"],
            "recall": pct(o["recall"]) if frauds else "n/a"}


def per_bin(data: pd.DataFrame, out: "Results") -> list[list]:
    y = data[LABEL].to_numpy() == 1
    frame = pd.DataFrame({"bin": bin_start(data.Time.to_numpy()), "n": 1, "alerts": out.alert,
                          "caught": out.alert & y, "false": out.alert & ~y, "missed": ~out.alert & y})
    return [[hh_mm(start), f"{r.n:,}", r.alerts, r.caught, r.false, r.missed]
            for start, r in frame.groupby("bin").sum().iterrows()]


def write(data: pd.DataFrame, test: pd.DataFrame, out: "Results", run_id: str, threshold: float,
          slice_desc: str, elapsed_s: float) -> dict:
    """Writes the report and returns the headline figures for the console."""
    served_offline, test_offline = offline_scores(run_id, data, test)
    y = data[LABEL].to_numpy()
    served = counts(y, out.score, threshold)
    par = parity(out, served_offline, threshold)
    lat = latency_summary(out.latency_ms)
    columns = {"Replay (API)": served, "Offline, same slice": counts(y, served_offline, threshold),
               "Offline, whole test window": counts(test[LABEL].to_numpy(), test_offline, threshold)}
    rows = [[name.capitalize()] + [f"{c[name]:,}" if isinstance(c[name], int) else c[name] for c in columns.values()]
            for name in served]

    sections = [
        "# Replay Report",
        f"Generated by `scripts/fraud/replay.py`. Run `{run_id[:8]}`, threshold {threshold:.6f}. "
        f"Data SHA-256 `{SHA256[:8]}…{SHA256[-3:]}`.  \n{slice_desc}, replayed through the API in {mm_ss(elapsed_s)}.",

        "## 1. Decisions",
        table(["", *columns], rows),
        "The whole-window column is the decision report's operational view; comparing recall with it shows how "
        "typical the slice is.",

        "## 2. Parity (served vs offline)",
        f"{len(y):,} scores from the API against the same run's model loaded offline: largest difference "
        f"{par['max_diff']:.3g}, alert decisions that differ: {par['mismatches']}.",

        "## 3. Latency (end to end, through the API)",
        table(["Requests", "Mean ms", "p50 ms", "p95 ms", "p99 ms", "Max ms", f"> {LATENCY_LIMIT_MS} ms",
               f"p99 ≤ {LATENCY_LIMIT_MS} ms"],
              [[f"{len(y):,}", *(f"{lat[k]:.1f}" for k in ("mean", "p50", "p95", "p99", "max")),
                f"{lat['over_limit']:.2%}", "pass" if lat["p99"] <= LATENCY_LIMIT_MS else "**fail**"]]),
        f"From request sent to answer received, on {platform.platform()}, {os.cpu_count()} logical cores; the "
        f"client and API share the machine. Requests went out at most {np.max(out.lag_ms):.1f} ms behind schedule.",

        f"## 4. Per {BIN_MIN} data minutes",
        table(["Data time", "Transactions", "Alerts", "Caught", "False alerts", "Missed"], per_bin(data, out)),
    ]
    REPORT.write_text("\n\n".join(sections) + "\n")
    return {**served, **par, "p99": lat["p99"]}
